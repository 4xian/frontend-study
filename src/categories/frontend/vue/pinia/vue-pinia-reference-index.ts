/** 将稳定定义转换为目录小节，并为 PRA1 至 PRA3 的 41 项发布真实目标。 */
function piniaReferenceSection(
  definition: PiniaStableReferenceSectionDefinition,
): ReferenceIndexSectionManifest {
  return {
    id: definition.id,
    title: definition.title,
    items: definition.items.map(
      ([id, name, officialUrl, sourceTag, depth, entryId, anchor, aliases]) => {
        const available = availableStableIds.has(id)
        return {
          id,
          name,
          officialUrl,
          aliases,
          sourceTag,
          depth,
          status: available ? ('available' as const) : ('planned' as const),
          target: available ? { entryId, anchor } : undefined,
        }
      },
    ),
  }
}

