/** 建立一条明确的来源处置。 */
const mapping = (sourceId, disposition) => ({ sourceId, disposition })

/** 建立一个具有独立正文深度的课程节点。 */
function lessonNode(definition) {
  const mappings = []
  if (definition.anchorSourceId) mappings.push(mapping(definition.anchorSourceId, 'lesson'))
  for (const sourceId of definition.mergedSourceIds ?? [])
    mappings.push(mapping(sourceId, 'merged'))
  return {
    ...definition,
    purpose: 'learn',
    depth: 'lesson',
    mappings,
  }
}

/** 建立一个仅因连续学习所需而加入的前置课程节点。 */
function prerequisiteNode(definition) {
  return lessonNode({
    ...definition,
    anchorSourceId: null,
    mergedSourceIds: [],
    origin: ['necessary-prerequisite'],
  })
}

/** 建立一个独立可检索的参考节点。 */
function referenceNode(definition) {
  return {
    ...definition,
    purpose: 'reference',
    collection: 'catalog',
    depth: 'reference',
    prerequisites: [],
    mappings: definition.sourceIds.map((sourceId) => mapping(sourceId, 'reference')),
  }
}

/** 建立一个只登记候选链路、不编写示例的项目节点。 */
function projectNode(definition) {
  return {
    ...definition,
    purpose: 'projects',
    collection: 'dzzz-app',
    level: 'advanced',
    depth: 'project',
    sourcePlanKey: 'project',
    mappings: (definition.sourceIds ?? []).map((sourceId) => mapping(sourceId, 'project-only')),
  }
}

